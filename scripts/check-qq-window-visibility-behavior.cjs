const assert = require('node:assert/strict');
const { FakeElement, installFakeDom, flushUi, privateConversation, createFakeFacade } = require('./helpers/qq-ui-fixture.cjs');
const flush = async () => { for (let i = 0; i < 12; i += 1) await flushUi(); };

async function exercise(kind) {
    global.HTMLElement = FakeElement;
    global.Element = FakeElement;
    global.HTMLFormElement = class extends FakeElement {};
    installFakeDom();
    const { createQQApp } = await import('../modules/qq-v2/ui/app.js');
    const conversation = { ...privateConversation('测试', 'c1'), kind, group: kind === 'group' ? { members: [], selfRole: 'member' } : undefined, canSend: true, request: { phase: 'idle' }, injection: {} };
    const { facade } = createFakeFacade({ initialConversations: [conversation] });
    facade.intent.openConversation = async () => ({ ok: true });
    let messages = Array.from({ length: 123 }, (_, i) => ({ messageId: 'm' + (i + 1), conversationId: 'c1', sequence: i + 1, senderType: 'self', senderId: '__self__', type: 'text', content: '消息' + (i + 1), storyTime: '' }));
    const calls = [];
    facade.query.messages = async (input) => {
        calls.push({ ...input });
        const older = messages.filter(m => !Number.isInteger(input.beforeSequence) || m.sequence < input.beforeSequence);
        let items = Number.isInteger(input.fromSequence) ? older.filter(m => m.sequence >= input.fromSequence) : older.slice(-input.limit);
        if (!items.length && Number.isInteger(input.fromSequence)) items = older.slice(-50);
        return { ok: true, page: { items, hasMore: older.length > items.length, nextBeforeSequence: items[0]?.sequence ?? null } };
    };
    let visible = true;
    let dirty = 0;
    const errors = [];
    const app = createQQApp({ facade, scopeId: 'scope-add-contact-ui', getSettings: () => ({}), isVisible: () => visible, onDeferredRender: () => { dirty += 1; }, onError: e => errors.push(e) });
    const root = new FakeElement(); root._rootConnected = true;
    app.mount(root); await flush();
    const viewport = root.querySelector('.yuzi-qq-viewport');
    await viewport.dispatch('click', { target: root.querySelector('[data-qq-conversation-id="c1"]').querySelector('button') });
    await flush();
    const stream = () => root.querySelector('[data-qq-message-stream="c1"]');
    const ids = () => stream().querySelectorAll('[data-qq-scroll-key]').map(n => n.dataset.qqScrollKey).filter(k => k.startsWith('message:'));
    assert.equal(ids().length, 50);
    const firstCalls = calls.length;
    stream().scrollTop = 0; await stream().dispatch('scroll'); await flush();
    assert.equal(ids().length, 100, '翻页必须保留100条，而不是重新读最新50条');
    assert.equal(calls.length, firstCalls + 1, '一次上翻只查询一页');
    stream().scrollTop = 0; await stream().dispatch('scroll'); await flush();
    assert.equal(ids().length, 123);
    const exhaustedCalls = calls.length;
    await stream().dispatch('scroll'); await flush();
    assert.equal(calls.length, exhaustedCalls, '没有更多时不再查询');
    messages = messages.filter(m => m.sequence !== 20).map(m => m.sequence === 30 ? { ...m, content: '已编辑' } : m);
    messages.push({ ...messages.at(-1), messageId: 'm124', sequence: 124, content: '新消息' });
    await app.refresh(); await flush();
    assert.equal(ids().length, 123);
    assert.ok(!ids().includes('message:m20'), '删除不能被旧缓存复活');
    assert.ok(root.querySelectorAll('*').some(node => node.textContent === '已编辑'), '窗口刷新展示编辑后的事实');
    assert.ok(ids().includes('message:m1') && ids().includes('message:m124'), '通知刷新保留历史并补新消息');
    const input = root.querySelector('.yuzi-qq-composer-input');
    input.value = '未发送草稿'; await input.dispatch('input'); await flush();
    const originalStream = stream(); const beforeHideCalls = calls.length;
    visible = false; app.suspend();
    await app.refresh(); await app.refresh(); await flush();
    assert.equal(calls.length, beforeHideCalls, '隐藏不启动消息显示查询');
    assert.equal(stream(), originalStream, '隐藏不替换页面');
    assert.ok(dirty > 0);
    visible = true; await app.refresh(); await flush();
    assert.ok(ids().includes('message:m1'));
    assert.equal(root.querySelector('.yuzi-qq-composer-input').value, '未发送草稿', '恢复后保留草稿');
    const query = facade.query.messages;
    let releaseRead, readStarted;
    const started = new Promise(resolve => { readStarted = resolve; });
    const readGate = new Promise(resolve => { releaseRead = resolve; });
    let slowOnce = true;
    facade.query.messages = async input => {
        const result = await query(input);
        if (slowOnce) { slowOnce = false; readStarted(); await readGate; }
        return result;
    };
    let commits = 0;
    const replace = viewport.replaceChildren.bind(viewport);
    viewport.replaceChildren = (...nodes) => { commits += 1; return replace(...nodes); };
    const oldRefresh = app.refresh(); await started;
    visible = false; app.suspend(); visible = true;
    messages = messages.filter(message => message.messageId !== 'm1');
    const latestRefresh = app.refresh(); releaseRead();
    await Promise.all([oldRefresh, latestRefresh]); await flush();
    assert.equal(commits, 1, '隐藏前的迟到渲染不提交，只有恢复后的画面提交');
    assert.ok(!ids().includes('message:m1'));
    await viewport.dispatch('click', { target: root.querySelector('[data-qq-back]') }); await flush();
    await viewport.dispatch('click', { target: root.querySelector('[data-qq-conversation-id="c1"]').querySelector('button') }); await flush();
    assert.equal(ids().length, 50, '从列表重新打开使用新的最新页窗口');
    app.destroy();
    assert.deepEqual(errors, []);
    console.log('[qq-window-visibility-behavior] ' + kind + ' passed');
}
(async () => { await exercise('private'); await exercise('group'); })().catch(error => { console.error(error); process.exitCode = 1; });
