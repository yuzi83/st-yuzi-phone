const assert = require('node:assert/strict');
const deferred = () => { let resolve; const promise = new Promise(r => { resolve = r; }); return { promise, resolve }; };
async function main() {
    const { createMessageWindow, reconcileMessageScrollAnchor } = await import('../modules/qq-v2/ui/message-window.js');
    let data = Array.from({ length: 280 }, (_, i) => ({ messageId: 'm' + i, sequence: i * 2, content: 'old' }));
    let active = true, gate = null, fail = false;
    const calls = [];
    const windows = createMessageWindow({ canRead: () => active, query: async input => {
        calls.push(input);
        const matching = data.filter(m => input.beforeSequence === undefined || m.sequence < input.beforeSequence);
        let items = input.fromSequence === undefined ? matching.slice(-50) : matching.filter(m => m.sequence >= input.fromSequence);
        if (!items.length && input.fromSequence !== undefined) items = matching.slice(-50);
        const result = fail ? { ok: false } : { ok: true, page: { items, hasMore: matching.length > items.length, nextBeforeSequence: items[0]?.sequence ?? null } };
        if (gate) await gate.promise;
        return result;
    } });
    await windows.load('a'); assert.equal(windows.get('a').items.length, 50);
    gate = deferred(); const blocked = gate;
    const older = windows.load('a', { prepend: true });
    assert.equal(windows.load('a', { prepend: true }), older, '重复触顶复用同一个请求');
    await Promise.resolve();
    const refreshed = windows.load('a');
    data = data.filter(m => m.messageId !== 'm270').map(m => m.messageId === 'm260' ? { ...m, content: 'edited' } : m);
    data.push({ messageId: 'new', sequence: 900, content: 'new' });
    gate = null; blocked.resolve(); await Promise.all([older, refreshed]);
    assert.equal(calls.length, 3);
    assert.ok(windows.get('a').items.some(m => m.messageId === 'm180'));
    assert.ok(!windows.get('a').items.some(m => m.messageId === 'm270'));
    assert.equal(windows.get('a').items.find(m => m.messageId === 'm260').content, 'edited');
    while (windows.get('a').hasMore) await windows.load('a', { prepend: true });
    assert.equal(windows.get('a').items.length, 280);
    assert.equal(new Set(windows.get('a').items.map(m => m.messageId)).size, 280);
    windows.reset('a'); await windows.load('a'); assert.equal(windows.get('a').items.length, 50);
    fail = true; const saved = windows.get('a'); await assert.rejects(windows.load('a', { prepend: true }));
    assert.equal(windows.get('a'), saved, '失败保留数据和游标');
    fail = false; await windows.load('a', { prepend: true }); assert.equal(windows.get('a').items.length, 100);
    gate = deferred(); const staleGate = gate; const stale = windows.load('a'); await Promise.resolve();
    active = false; assert.equal(windows.invalidate(), true, '暂停能检测进行中消息读取');
    active = true; windows.reset('a'); gate = null; await windows.load('a'); const fresh = windows.get('a');
    staleGate.resolve(); assert.equal(await stale, null); assert.equal(windows.get('a'), fresh, '旧浏览周期不能覆盖同名新会话窗口');
    let rejectRead;
    const rejected = createMessageWindow({ query: () => new Promise((_resolve, reject) => { rejectRead = reject; }) });
    const staleFailure = rejected.load('a'); await Promise.resolve(); rejected.invalidate();
    rejectRead(new Error('late failure'));
    assert.equal(await staleFailure, null, '旧浏览周期的迟到异常也不得污染新页面');
    data = []; await windows.load('a'); assert.equal(windows.get('a').items.length, 0);
    windows.clear(); assert.equal(windows.get('a').items.length, 0);
    const anchor = { registrationKey: 'private-chat', state: { mode: 'anchor', key: 'b', viewportOffset: 12 } };
    assert.equal(reconcileMessageScrollAnchor(anchor, ['a', 'b', 'c'], ['a', 'c']).state.key, 'c');
    assert.equal(reconcileMessageScrollAnchor(anchor, ['a', 'b'], ['a']).state.key, 'a');
    assert.equal(reconcileMessageScrollAnchor(anchor, ['b'], []), null);
    assert.equal(reconcileMessageScrollAnchor(anchor, ['a', 'b'], ['b']), anchor);
    console.log('[qq-message-window-behavior] passed');
}
main().catch(error => { console.error(error); process.exitCode = 1; });
