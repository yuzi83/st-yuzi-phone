import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { createRuntimeV1 } from '../preview/runtime-v1.js';
import { createPreviewImageActions } from '../preview/image-actions.js';
const canvas = JSON.parse(await fs.readFile(new URL('../examples/image-avatar/canvas.json', import.meta.url), 'utf8'));
const row = { 人物编号: 'hero', 性别: '女', 年龄: 22, 外貌特征: '短发', 身份: '旅人' };
const initialState = { version: 1, sheetKey: 'hero', tableName: '人物表', headers: Object.keys(row), rows: [Object.values(row)] };
const declaration = { imageGeneration: { canvases: [canvas] } };
const originalFetch = globalThis.fetch;
globalThis.fetch = () => { throw new Error('模拟不得联网'); };
try {
  const runtime = createRuntimeV1({ root: {}, initialState, declaration });
  let context = await runtime.mountModule({ mount() {} });
  const a = context.actions;
  for (const name of ['generateImage', 'readImage', 'getImageGenerationState', 'subscribeImageGeneration']) assert.equal(typeof a[name], 'function');
  assert.equal((await a.readImage('avatar', row)).status, 'empty');
  assert.equal((await a.getImageGenerationState('avatar')).available, true);
  assert.equal((await a.generateImage('missing', row)).status, 'invalid-input');
  assert.equal((await a.generateImage('avatar', { ...row, 人物编号: '' })).status, 'invalid-target');
  const pending = a.generateImage('avatar', row);
  assert.equal((await a.generateImage('avatar', row)).status, 'busy');
  const generated = await pending;
  assert.equal(generated.status, 'generated');
  assert.ok(decodeURIComponent(generated.imagePath).includes('TEST ONLY'));
  runtime.setImageScenario('failed');
  const failure = await a.generateImage('avatar', row);
  assert.equal(failure.status, 'failed');
  assert.equal(failure.previousImagePath, generated.imagePath);
  assert.equal((await a.readImage('avatar', row)).imagePath, generated.imagePath);
  let notifications = 0;
  const off = a.subscribeImageGeneration(() => notifications++);
  runtime.setImageScenario('disabled');
  assert.equal(notifications, 1);
  assert.equal((await a.generateImage('avatar', row)).status, 'disabled');
  off(); off();
  runtime.setImageScenario('unavailable');
  assert.equal(notifications, 1);
  assert.equal((await a.getImageGenerationState('avatar', row)).available, false);
  runtime.setImageScenario('generated');
  runtime.updateState({ ...initialState, version: 2, rows: [Object.values(row), Object.values(row)] });
  assert.equal((await a.generateImage('avatar', row)).status, 'invalid-target');
  runtime.updateState({ ...initialState, version: 3 });
  const late = a.generateImage('avatar', row);
  await runtime.unmount();
  assert.equal((await late).status, 'stale');
  context = await runtime.mountModule({ mount() {} });
  assert.equal((await context.actions.readImage('avatar', row)).imagePath, generated.imagePath);
  assert.equal((await a.generateImage('avatar', row)).status, 'stale');

  runtime.setImageScenario('disabled');
  const upload = await context.actions.saveImage('avatar', row, new Blob([Uint8Array.from([137,80,78,71,13,10,26,10])], { type: 'image/png' }));
  assert.equal(upload.status, 'saved');
  assert.equal((await context.actions.readImage('avatar', row)).imagePath, upload.imagePath);
  runtime.setImageScenario('failed');
  assert.equal((await context.actions.deleteImage('avatar', row)).status, 'failed');
  assert.equal((await context.actions.readImage('avatar', row)).imagePath, upload.imagePath);
  runtime.setImageScenario('disabled');
  assert.equal((await context.actions.deleteImage('avatar', row)).status, 'deleted');
  await runtime.unmount();
  context = await runtime.mountModule({ mount() {} });
  assert.deepEqual(await context.actions.readImage('avatar', row), { ok: true, status: 'empty', cleared: true });
  assert.equal((await context.actions.saveImage('avatar', row, 'invalid')).status, 'invalid-input');
  await runtime.destroy();
  const legacy = createRuntimeV1({ root: {}, initialState });
  assert.equal((await legacy.mountModule({ mount() {} })).actions.generateImage, undefined);
  await legacy.destroy();
  // The documented composition is visible in the mock log, including optional text.
  const logs = [];
  const controller = new AbortController();
  const mock = createPreviewImageActions({ declaration, getState: () => initialState, signal: controller.signal, delayMs: 0, onLog: log => logs.push(log) });
  await mock.actions.generateImage('avatar', row);
  assert.equal(logs[0].details.prompt, '性别：女\n年龄：22\n外貌特征：短发\n身份：旅人\n' + canvas.promptSuffix);
  controller.abort();
  const frame = await fs.readFile(new URL('../preview/frame.html', import.meta.url), 'utf8');
  assert.ok(frame.includes("connect-src 'none'"));
  assert.ok(frame.includes('img-src data: blob:'));
} finally { globalThis.fetch = originalFetch; }
console.log('[preview-image-actions-tests] 通过；仅本地测试图、成功/失败/关闭/不可用、防重、身份校验、清理与重挂载');
